import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {Workbook, SpreadsheetFile} from '@oai/artifact-tool';
const dir = fileURLToPath(new URL('./', import.meta.url));
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('HCP导入');
sheet.showGridLines = false;
sheet.getRange('A1:B1').values = [['医生姓名', '手机号']];
sheet.getRange('A1:B21').format.font = {name: 'Arial', size: 11};
sheet.getRange('A1:B21').format.rowHeight = 25;
sheet.getRange('A1:B21').format.columnWidth = 24;
sheet.getRange('A1:B1').format.fill = '#1677FF';
sheet.getRange('A1:B1').format.font = {name: 'Arial', size: 11, bold: true, color: '#FFFFFF'};
sheet.getRange('A1:B1').format.horizontalAlignment = 'center';
sheet.getRange('A2:B21').format.fill = '#FFFBE6';
sheet.getRange('A2:B501').setNumberFormat('@');
sheet.freezePanes.freezeRows(1);
workbook.recalculate();
console.log((await workbook.inspect({kind: 'table', range: 'HCP导入!A1:B3', include: 'values', tableMaxRows: 3, tableMaxCols: 2})).ndjson);
const image = await workbook.render({sheetName: 'HCP导入', range: 'A1:B8', format: 'png', scale: 1.5});
await fs.writeFile(`${dir}/template-preview.png`, new Uint8Array(await image.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(workbook)).save(`${dir}/HCP批量导入模板.xlsx`);
